def codex_to_claude(state, args):
    project = args.project or munge_cwd(os.path.expanduser("~"))
    if project in ("", ".", "..") or "/" in project or "\\" in project:
        raise SyncError("--project must name one Claude project directory")
    memdir = os.path.join(CLAUDE_PROJECTS, project, "memory")
    target = os.path.join(memdir, CLAUDE_OWNED_NAME)
    summary = read(CODEX_SUMMARY, default=None)
    available = summary is not None
    if not available:
        log("codex->claude: no source summary, leaving the last snapshot unchanged")
        return 0
    previous = read(target, default=None)
    digest = sha(summary)
    body = (
        "---\n"
        "name: codex-memory-sync\n"
        "description: Auto-synced Codex memory — regenerated by memory-sync.py\n"
        "metadata:\n"
        "  type: project\n"
        "---\n\n"
        f"{MARKER}\n\n"
        f"{summary.strip()}\n"
    )
    changed = previous != body
    if changed and not write_owned(target, body, args.dry_run, state):
        return 0
    added = append_once(os.path.join(memdir, "MEMORY.md"), CLAUDE_OWNED_NAME, INDEX_LINE, args.dry_run) if available else False
    if not args.dry_run:
        state["codex_summary_sha"] = digest
    if not changed and not added:
        log("codex->claude: unchanged")
        return 0
    write_output(f"{'would sync' if args.dry_run else 'synced'} codex->claude: {target}"
          + (" (+ MEMORY.md index)" if added else ""))
    return 1


def _tidy(s):
    s = " ".join(s.split()).strip().strip('"').strip("'").strip()
    return s if len(s) <= DESC_CAP else s[:DESC_CAP].rsplit(" ", 1)[0] + "…"


def describe(text):
    """One line about a memory file: its frontmatter description, else its first prose line."""
    if text.startswith("---"):
        m = re.search(r"^description:\s*(.+)$", text, re.M)
        if m:
            return _tidy(m.group(1))
        text = strip_frontmatter(text)   # else `name:` etc. would masquerade as prose
    for line in text.split("\n"):
        s = line.strip()
        if s and not s.startswith(("---", "#")):
            return _tidy(s)
    return ""


def memory_groups():
    out = []
    for project, memdir in memory_dirs():
        files = [f for f in sorted(os.listdir(memdir))
                 if f.endswith(".md") and f not in SKIP_NAMES]
        if files:
            out.append((project, memdir, files))
    return out


def build_full(groups):
    chunks = []
    for project, memdir, files in groups:
        chunks.append(f"## project: {project}")
        for name in files:
            chunks.append(f"### {name}")
            chunks.append(strip_frontmatter(read(os.path.join(memdir, name))).strip())
            chunks.append("")
    return "\n".join(chunks).rstrip() + "\n"


def build_index(groups):
    """A table of contents with absolute paths. Codex reads only what it needs."""
    chunks = []
    for project, memdir, files in groups:
        chunks.append(f"## project: {project}  ({memdir})")
        for name in files:
            chunks.append(f"- {name} — {describe(read(os.path.join(memdir, name)))}")
        chunks.append("")
    return "\n".join(chunks).rstrip() + "\n"


def build_auto(groups, budget):
    """Read each source once; stop retaining full text when it cannot fit."""
    full_chunks, index_chunks = [], []
    estimate = 0
    for project, memdir, files in groups:
        heading = f"## project: {project}"
        index_chunks.append(f"## project: {project}  ({memdir})")
        if full_chunks is not None:
            full_chunks.append(heading)
            estimate += len(heading.encode("utf-8")) + 1
        for name in files:
            content = read(os.path.join(memdir, name))
            index_chunks.append(f"- {name} — {describe(content)}")
            if full_chunks is not None:
                body = strip_frontmatter(content).strip()
                pieces = [f"### {name}", body, ""]
                full_chunks.extend(pieces)
                estimate += sum(len(piece.encode("utf-8")) + 1 for piece in pieces)
                trailing = 1 if body else 2
                if estimate - trailing > budget:
                    full_chunks = None
        index_chunks.append("")
    if full_chunks is not None:
        full = "\n".join(full_chunks).rstrip() + "\n"
        if len(full.encode("utf-8")) <= budget:
            return "full", full
    return "index", "\n".join(index_chunks).rstrip() + "\n"


def claude_to_codex(state, args):
    groups = memory_groups()
    available = bool(groups)
    if not available:
        log("claude->codex: no source files, leaving the last snapshot unchanged")
        return 0
    previous = read(CODEX_OWNED, default=None)
    n_files = sum(len(files) for _, _, files in groups)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    def note(mode):
        return (f"{n_files} files, full text" if mode == "full" else
                f"{n_files} files across {len(groups)} projects, index only — read a path above for its full text")

    def render(mode, core, date):
        return (f"# Claude Code Memory\n{MARKER}\nupdated: {date}\n"
                f"scope: Auto-synced from Claude Code memory files on this host\n"
                f"mode: {note(mode)}\n\n{core}")

    mode = args.mode
    if mode == "auto":
        overhead = len(render("full", "", stamp).encode("utf-8"))
        mode, body_core = build_auto(groups, args.warn_bytes - overhead)
    elif mode == "index":
        body_core = build_index(groups)
    else:
        body_core = build_full(groups)
    digest = sha(mode + body_core)
    previous_stamp = re.search(r"^updated: ([^\n]+)$", previous or "", re.M)
    old_date = previous_stamp.group(1) if previous_stamp else stamp
    unchanged = previous == render(mode, body_core, old_date)
    body = previous if unchanged else render(mode, body_core, stamp)
    if not unchanged and not write_owned(CODEX_OWNED, body, args.dry_run, state):
        return 0
    size = len(body.encode("utf-8"))
    already = "claude_code_sync" in read(CODEX_AGENTS)
    added = False
    if available:
        if size > args.warn_bytes and not already:
            if not unchanged:
                print(f"not pointing {os.path.basename(CODEX_AGENTS)} at a {size // 1024}K bundle; "
                      "use index mode or raise --warn-bytes", file=sys.stderr)
        else:
            if size > args.warn_bytes and not unchanged:
                print(f"warning: {CODEX_OWNED} exceeds --warn-bytes", file=sys.stderr)
            added = append_once(CODEX_AGENTS, "claude_code_sync", POINTER, args.dry_run)
    if not args.dry_run:
        state["claude_memory_sha"] = digest
    if unchanged and not added:
        log("claude->codex: unchanged")
        return 0
    write_output(f"{'would sync' if args.dry_run else 'synced'} claude->codex: {CODEX_OWNED} "
          f"[{mode}, {size // 1024}K]" + (" (+ AGENTS.md pointer)" if added else ""))
    return 1


def configure_paths(codex_home=None, claude_home=None, state_dir=None):
    global CODEX_HOME, CLAUDE_HOME, CLAUDE_PROJECTS, CODEX_MEM, CODEX_SUMMARY, CODEX_OWNED, CODEX_AGENTS
    global STATE_DIR, STATE_FILE, LOCK_FILE, POINTER
    CODEX_HOME = str(Path(codex_home or CODEX_HOME).expanduser().absolute())
    CLAUDE_HOME = str(Path(claude_home or CLAUDE_HOME).expanduser().absolute())
    CLAUDE_PROJECTS = os.path.join(CLAUDE_HOME, "projects")
    CODEX_MEM = os.path.join(CODEX_HOME, "memories")
    CODEX_SUMMARY = os.path.join(CODEX_MEM, "memory_summary.md")
    CODEX_OWNED = os.path.join(CODEX_MEM, "claude_code_sync.md")
    CODEX_AGENTS = os.path.join(CODEX_HOME, "AGENTS.md")
    STATE_DIR = str(Path(state_dir or STATE_DIR).expanduser().absolute())
    STATE_FILE = os.path.join(STATE_DIR, "memory-state.json")
    LOCK_FILE = os.path.join(STATE_DIR, "memory.lock")
    POINTER = f"At session start, also read {CODEX_OWNED} for Claude Code memory about this host's projects and user preferences."


def _main(argv=None):
    global VERBOSE
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--to-claude", action="store_true", help="only sync codex -> claude")
    ap.add_argument("--to-codex", action="store_true", help="only sync claude -> codex")
    ap.add_argument("--project", help="Claude project dir to receive Codex memory "
                                      "(default: the one matching your home dir)")
    ap.add_argument("--mode", choices=("auto", "full", "index"), default="auto",
                    help="what to hand Codex: full memory text, or an index of names, "
                         "descriptions and paths. auto (default) picks full when it fits "
                         "under --warn-bytes, else index")
    ap.add_argument("--warn-bytes", type=int, default=65536,
                    help="warn when the bundle Codex must read exceeds this size "
                         "(default 65536; it costs context on every session)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--quiet", action="store_true", help="no output when idle (for cron)")
    ap.add_argument("--codex-home", help="explicit Codex data root for automation")
    ap.add_argument("--claude-home", help="explicit Claude data root for automation")
    ap.add_argument("--state-dir", help="explicit memory state directory for automation")
    args = ap.parse_args(argv)
    VERBOSE = args.verbose
    if args.to_codex and args.to_claude:
        ap.error("choose only one of --to-codex and --to-claude")
    if args.warn_bytes <= 0:
        ap.error("--warn-bytes must be positive")
    configure_paths(args.codex_home, args.claude_home, args.state_dir)

    lock = None
    if not args.dry_run:
        lock = acquire_lock(LOCK_FILE)
        if lock is None:
            return 0

    try:
        state = load_state()
        n = 0
        if not args.to_codex:
            n += codex_to_claude(state, args)
        if not args.to_claude:
            n += claude_to_codex(state, args)
        if not args.dry_run:
            save_state(state)
        if n == 0 and not args.quiet:
            print("memory-sync: nothing to do")
        return 0
    finally:
        if lock is not None:
            lock.close()



def main(argv=None):
    try:
        return _main(argv)
    except (SyncError, OSError, ValueError) as exc:
        print(f"memory-sync: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
